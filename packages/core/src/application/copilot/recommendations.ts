/**
 * «Recomendaciones del Copilot» in «Estadísticas» (C1 · Paso 4, ADR-054): generated on
 * request by any member, the latest set kept with its facts and its date. Never publishes nor
 * changes anything: each recommendation links to where a person of the team does it.
 */

export interface SavedRecommendations {
  readonly id: string;
  readonly createdAt: string;
  /** The visits period the facts were computed on. */
  readonly from: string;
  readonly to: string;
  readonly facts: readonly RecommendationFact[];
  readonly items: readonly Recommendation[];
  /** Generated by the person reading them. */
  readonly mine: boolean;
}

export type SaveRecommendationsOutcome =
  { readonly status: "saved"; readonly id: string } | { readonly status: "invalid" | "forbidden" };

/** With the signed-in user's session (the RPCs re-check the role, the facts and the numbers). */
export interface RecommendationsRepository {
  latest(tenantId: string): Promise<SavedRecommendations | null>;
  save(input: {
    readonly tenantId: string;
    readonly aiRequestId: string;
    readonly from: string;
    readonly to: string;
    readonly facts: readonly RecommendationFact[];
    readonly items: readonly Recommendation[];
  }): Promise<SaveRecommendationsOutcome>;
}

/** After this many days the panel says to generate new ones. */
export const RECOMMENDATIONS_FRESH_DAYS = 7;

export function loadRecommendations(
  membership: OrganizationMembership,
  repository: RecommendationsRepository,
): Promise<SavedRecommendations | null> {
  return repository.latest(membership.tenantId);
}

export interface GenerateRecommendationsDeps {
  readonly recommendations: RecommendationsRepository;
  readonly copilot: CopilotRepository;
  readonly statistics: StatisticsRepository;
  readonly questions: UnansweredQuestionsRepository;
  readonly ai: CopilotAiRunner;
  readonly now?: () => Date;
}

export type GenerateRecommendationsOutcome =
  | { readonly status: "saved"; readonly count: number; readonly dropped: number }
  | { readonly status: "notice"; readonly message: string }
  | { readonly status: "forbidden" };

export const RECOMMENDATION_NOTICES = {
  nothing:
    "El Copilot no escribió recomendaciones que se apoyen en las cifras de la plataforma. Prueba de nuevo en un momento.",
  failed: "No pudimos guardar las recomendaciones. Prueba de nuevo.",
} as const;

function today(now: Date, timezone: string): string {
  try {
    return new Intl.DateTimeFormat("es", {
      timeZone: timezone,
      weekday: "long",
      day: "numeric",
      month: "long",
      year: "numeric",
    }).format(now);
  } catch {
    return now.toISOString().slice(0, 10);
  }
}

/** The unanswered questions as the facts read them. */
export function recommendationQuestions(
  data: UnansweredQuestionsData,
): RecommendationInput["questions"] {
  return {
    from: data.from,
    to: data.to,
    total: data.total,
    people: data.people,
    distinct: data.groups.length,
    groups: data.groups.map((group) => ({
      text: group.text,
      times: group.times,
      people: group.people,
      lastDay: group.lastDay,
      place: group.pages.find((page) => page.title)?.title ?? null,
    })),
  };
}

/** The places published without pending changes: «publicar» them asks for nothing. */
export function publishedPlaces(snapshot: readonly CopilotSnapshotRow[]): Set<string> {
  return new Set(snapshot.filter((row) => row.status === "published").map((row) => row.contentId));
}

export interface RecommendationRun {
  readonly tenantId: string;
  /** The municipality's name. */
  readonly site: string;
  readonly timezone: string;
  readonly now: Date;
  /** The person who asked; null when the platform does (the monthly report). */
  readonly actorId: string | null;
  readonly statistics: StatisticsSummary;
  readonly period?: RecommendationPeriod;
  readonly questions: UnansweredQuestionsData;
  readonly review: readonly CopilotReviewRow[];
  readonly snapshot: readonly CopilotSnapshotRow[];
  readonly ai: CopilotAiRunner;
}

export type RecommendationRunOutcome =
  | {
      readonly status: "answered";
      readonly requestId: string;
      readonly facts: RecommendationFact[];
      readonly items: Recommendation[];
      readonly dropped: number;
    }
  /** The model answered, but nothing it wrote rests on the facts. */
  | { readonly status: "nothing"; readonly dropped: number }
  | { readonly status: "refused"; readonly outcome: AiRefusal };

/** Computes the facts, asks the model once and keeps what rests on the facts. */
export async function runRecommendations(
  run: RecommendationRun,
): Promise<RecommendationRunOutcome> {
  const facts = recommendationFacts({
    statistics: run.statistics,
    ...(run.period ? { period: run.period } : {}),
    questions: recommendationQuestions(run.questions),
    review: run.review,
    snapshot: run.snapshot,
  });
  const messages = recommendationMessages({
    site: run.site,
    today: today(run.now, run.timezone),
    facts,
  });
  const result = await run.ai(
    {
      tenantId: run.tenantId,
      profile: "copilot",
      reserveTokens: reservationFor("copilot", messages),
      actorId: run.actorId,
    },
    async (call) => (await call({ messages })).text,
  );
  if (result.outcome !== "answered") return { status: "refused", outcome: result.outcome };
  const parsed = parseRecommendations(result.value, facts, publishedPlaces(run.snapshot));
  if (parsed.items.length === 0) return { status: "nothing", dropped: parsed.dropped };
  return {
    status: "answered",
    requestId: result.requestId,
    facts,
    items: parsed.items,
    dropped: parsed.dropped,
  };
}

/** «Generar recomendaciones» in «Estadísticas»: the last 30 days. Any member. */
export async function generateRecommendations(
  membership: OrganizationMembership,
  actorId: string,
  deps: GenerateRecommendationsDeps,
): Promise<GenerateRecommendationsOutcome> {
  const now = (deps.now ?? (() => new Date()))();
  const [stats, questions, review, snapshot] = await Promise.all([
    loadStatistics(membership, deps.statistics, "30-dias", now),
    deps.questions.unansweredQuestions(membership.tenantId, 30),
    deps.copilot.review(membership.tenantId),
    deps.copilot.snapshot(membership.tenantId),
  ]);
  const run = await runRecommendations({
    tenantId: membership.tenantId,
    site: membership.displayName,
    timezone: snapshot.timezone,
    now,
    actorId,
    statistics: stats.summary,
    questions,
    review,
    snapshot: snapshot.items,
    ai: deps.ai,
  });
  if (run.status === "refused") {
    return { status: "notice", message: COPILOT_NOTICES[run.outcome] };
  }
  if (run.status === "nothing") {
    return { status: "notice", message: RECOMMENDATION_NOTICES.nothing };
  }
  const saved = await deps.recommendations.save({
    tenantId: membership.tenantId,
    aiRequestId: run.requestId,
    from: stats.summary.range.from,
    to: stats.summary.range.to,
    facts: run.facts,
    items: run.items,
  });
  if (saved.status === "forbidden") return { status: "forbidden" };
  if (saved.status !== "saved") {
    return { status: "notice", message: RECOMMENDATION_NOTICES.failed };
  }
  return { status: "saved", count: run.items.length, dropped: run.dropped };
}

// ── What the panel shows ────────────────────────────────────────────────────

export interface RecommendationLink {
  readonly label: string;
  readonly href: string;
}

/**
 * Where a recommendation leads: the editors of what its facts point at, never the model's.
 * With `names` (content id → its name, from the snapshot), each link says which place it
 * opens, so three «Abrir en el editor» never sit side by side.
 */
export function recommendationLinks(
  membership: OrganizationMembership,
  item: Recommendation,
  facts: readonly RecommendationFact[],
  names: ReadonlyMap<string, string> = new Map(),
): RecommendationLink[] {
  const org = membership.slug;
  const editing = canPropose(membership);
  const links: RecommendationLink[] = [];
  const seen = new Set<string>();
  const add = (label: string, href: string) => {
    if (seen.has(href)) return;
    seen.add(href);
    links.push({ label, href });
  };
  const quoted = (text: string) => `«${text.replace(/[«»]/gu, "")}»`;
  const targets = item.facts
    .map((id) => facts.find((fact) => fact.id === id)?.target)
    .filter((target): target is RecommendationTarget => target !== null && target !== undefined);
  for (const target of targets) {
    switch (target.type) {
      case "content": {
        const name = names.get(target.contentId);
        add(
          name ? `Abrir ${quoted(name)} en el editor` : "Abrir en el editor",
          COPILOT_PATHS.editor(org, target.kind, target.contentId),
        );
        if (editing && target.proposable) {
          add(
            name ? `Proponer un texto para ${quoted(name)}` : "Proponer con el Copilot",
            COPILOT_PATHS.propose(org, { type: "content", contentId: target.contentId }),
          );
        }
        break;
      }
      case "scene": {
        const name = names.get(target.contentId);
        add(
          name ? `Abrir el tour de ${quoted(name)}` : "Abrir el tour",
          COPILOT_PATHS.tour(org, target.tourId),
        );
        if (editing) {
          add(
            name
              ? `Proponer la descripción de la escena (tour de ${quoted(name)})`
              : "Proponer con el Copilot",
            COPILOT_PATHS.propose(org, {
              type: "scene",
              tourId: target.tourId,
              sceneId: target.sceneId,
            }),
          );
        }
        break;
      }
      case "question":
        add(
          `Probar ${quoted(target.question.length > 80 ? `${target.question.slice(0, 79).trimEnd()}…` : target.question)} en «Conocimiento del asistente»`,
          `/o/${org}/conocimiento?pregunta=${encodeURIComponent(target.question)}`,
        );
        break;
      case "agenda":
        add("Abrir la agenda", `/o/${org}/agenda`);
        break;
    }
  }
  return links;
}

/** Days since they were generated, in the municipality's calendar (approximately). */
export function recommendationsAge(saved: SavedRecommendations, now: Date = new Date()): number {
  const created = new Date(saved.createdAt).getTime();
  return Math.max(0, Math.floor((now.getTime() - created) / 86_400_000));
}
