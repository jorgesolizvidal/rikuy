/**
 * «Recomendaciones del Copilot» in «Estadísticas» (C1 · Paso 4, ADR-054): generated on
 * request by any member, the latest set kept with its facts and its date. Never publishes nor
 * changes anything: each recommendation links to where a person of the team does it.
 */

export interface SavedRecommendations {
  readonly id: string;
  readonly createdAt: string;
  /** The visits period the facts were computed on. */
  readonly from: string;
  readonly to: string;
  readonly facts: readonly RecommendationFact[];
  readonly items: readonly Recommendation[];
  /** Generated by the person reading them. */
  readonly mine: boolean;
}

export type SaveRecommendationsOutcome =
  { readonly status: "saved"; readonly id: string } | { readonly status: "invalid" | "forbidden" };

/** With the signed-in user's session (the RPCs re-check the role, the facts and the numbers). */
export interface RecommendationsRepository {
  latest(tenantId: string): Promise<SavedRecommendations | null>;
  save(input: {
    readonly tenantId: string;
    readonly aiRequestId: string;
    readonly from: string;
    readonly to: string;
    readonly facts: readonly RecommendationFact[];
    readonly items: readonly Recommendation[];
  }): Promise<SaveRecommendationsOutcome>;
}

/** After this many days the panel says to generate new ones. */
export const RECOMMENDATIONS_FRESH_DAYS = 7;

export function loadRecommendations(
  membership: OrganizationMembership,
  repository: RecommendationsRepository,
): Promise<SavedRecommendations | null> {
  return repository.latest(membership.tenantId);
}

export interface GenerateRecommendationsDeps {
  readonly recommendations: RecommendationsRepository;
  readonly copilot: CopilotRepository;
  readonly statistics: StatisticsRepository;
  readonly questions: UnansweredQuestionsRepository;
  readonly ai: CopilotAiRunner;
  readonly now?: () => Date;
}

export type GenerateRecommendationsOutcome =
  | { readonly status: "saved"; readonly count: number; readonly dropped: number }
  | { readonly status: "notice"; readonly message: string }
  | { readonly status: "forbidden" };

export const RECOMMENDATION_NOTICES = {
  nothing:
    "El Copilot no escribió recomendaciones que se apoyen en las cifras de la plataforma. Prueba de nuevo en un momento.",
  failed: "No pudimos guardar las recomendaciones. Prueba de nuevo.",
} as const;

function today(now: Date, timezone: string): string {
  try {
    return new Intl.DateTimeFormat("es", {
      timeZone: timezone,
      weekday: "long",
      day: "numeric",
      month: "long",
      year: "numeric",
    }).format(now);
  } catch {
    return now.toISOString().slice(0, 10);
  }
}

/** Computes the facts, asks the model once and keeps what rests on the facts. Any member. */
export async function generateRecommendations(
  membership: OrganizationMembership,
  actorId: string,
  deps: GenerateRecommendationsDeps,
): Promise<GenerateRecommendationsOutcome> {
  const now = (deps.now ?? (() => new Date()))();
  const [stats, questions, review, snapshot] = await Promise.all([
    loadStatistics(membership, deps.statistics, "30-dias", now),
    deps.questions.unansweredQuestions(membership.tenantId, 30),
    deps.copilot.review(membership.tenantId),
    deps.copilot.snapshot(membership.tenantId),
  ]);
  const facts = recommendationFacts({
    statistics: stats.summary,
    questions: {
      from: questions.from,
      to: questions.to,
      total: questions.total,
      people: questions.people,
      distinct: questions.groups.length,
      groups: questions.groups.map((group) => ({
        text: group.text,
        times: group.times,
        people: group.people,
        lastDay: group.lastDay,
        place: group.pages.find((page) => page.title)?.title ?? null,
      })),
    },
    review,
    snapshot: snapshot.items,
  });
  const messages = recommendationMessages({
    site: membership.displayName,
    today: today(now, snapshot.timezone),
    facts,
  });
  const result = await deps.ai(
    {
      tenantId: membership.tenantId,
      profile: "copilot",
      reserveTokens: reservationFor("copilot", messages),
      actorId,
    },
    async (call) => (await call({ messages })).text,
  );
  if (result.outcome !== "answered") {
    return { status: "notice", message: COPILOT_NOTICES[result.outcome] };
  }
  const parsed = parseRecommendations(result.value, facts);
  if (parsed.items.length === 0) {
    return { status: "notice", message: RECOMMENDATION_NOTICES.nothing };
  }
  const saved = await deps.recommendations.save({
    tenantId: membership.tenantId,
    aiRequestId: result.requestId,
    from: stats.summary.range.from,
    to: stats.summary.range.to,
    facts,
    items: parsed.items,
  });
  if (saved.status === "forbidden") return { status: "forbidden" };
  if (saved.status !== "saved") {
    return { status: "notice", message: RECOMMENDATION_NOTICES.failed };
  }
  return { status: "saved", count: parsed.items.length, dropped: parsed.dropped };
}

